function safeParseJson(text) {
  if (!text) return null;
  let clean = text.trim();
  // Strip markdown code fences if present
  clean = clean.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '').trim();
  try {
    return JSON.parse(clean);
  } catch (e) {
    const match = clean.match(/\{[\s\S]*\}/);
    if (match) {
      try {
        return JSON.parse(match[0]);
      } catch (err) {}
    }
    // If LLM returned raw conversational text instead of JSON, treat it directly as replyText!
    return {
      replyText: clean,
      isOrderReady: false,
      isEscalated: false,
      order: null,
    };
  }
}

async function callGemini(apiKey, contents, attempt = 1) {
  const targetUrl = attempt === 1 ? GEMINI_API_URL : GEMINI_BACKUP_URL;
  const res = await fetch(`${targetUrl}?key=${apiKey}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      system_instruction: {
        parts: [{ text: buildSystemPrompt() }],
      },
      contents,
      generationConfig: {
        temperature: 0.6,
        responseMimeType: 'application/json',
      },
    }),
  });

  if (!res.ok) {
    const errText = await res.text();
    console.error(`[AI] Gemini API HTTP error (attempt ${attempt}):`, res.status, errText);

    // If rate-limited or temporarily unavailable, retry once after 1.5 seconds with backup model
    if ((res.status === 429 || res.status === 503 || res.status === 404) && attempt === 1) {
      console.log('[AI] Retrying with backup Gemini model after 1500ms...');
      await new Promise((resolve) => setTimeout(resolve, 1500));
      return callGemini(apiKey, contents, 2);
    }

    throw new Error(`Gemini error: ${res.status}`);
  }

  const data = await res.json();
  const candidateText = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!candidateText) {
    throw new Error('Empty response from Gemini API');
  }

  return safeParseJson(candidateText);
}

/**
 * Handles incoming customer message using Gemini Flash.
 */
export async function generateBotResponse(userMessage, sessionHistory = []) {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey) {
    console.warn('[AI] GEMINI_API_KEY is not defined. Using fallback response.');
    return {
      replyText: 'გამარჯობა! 🐾 მადლობა „ხრამუნასთან“ დაკავშირებისთვის. რომელი პროდუქტი ან შეკითხვა გაინტერესებთ ჩვენს ნატურალურ სნექებზე?',
      isOrderReady: false,
    };
  }

  const contents = [];

  // Deduplicate: filter out current userMessage if it was already pushed to session history
  const historyToUse = sessionHistory.filter((item, idx) => {
    if (idx === sessionHistory.length - 1 && item.role === 'user' && item.text === userMessage) {
      return false;
    }
    return true;
  });

  // Append last session history messages (keep last 8 turns for speed and focus)
  const recentHistory = historyToUse.slice(-8);
  for (const item of recentHistory) {
    contents.push({
      role: item.role === 'assistant' || item.role === 'model' ? 'model' : 'user',
      parts: [{ text: item.text }],
    });
  }

  // Append latest user message exactly once
  contents.push({
    role: 'user',
    parts: [{ text: userMessage }],
  });

  try {
    const parsed = await callGemini(apiKey, contents);
    if (parsed && parsed.replyText) {
      // Deterministic cleanup: strip awkward calques & nonsensical phrases
      parsed.replyText = parsed.replyText
        .replace(/რომელმა(\s+უფრო)?\s+მოგეწონათ/gi, 'რომელი$1 მოგეწონათ')
        .replace(/რომელმა\s+გირჩევნიათ/gi, 'რომელი გირჩევნიათ')
        .replace(/რომელმა\s+მოგწონთ/gi, 'რომელი მოგწონთ')
        .replace(/რომელმა\s+გაინტერესებთ/gi, 'რომელი გაინტერესებთ')
        .replace(/რომელმა\s+შეარჩიოთ/gi, 'რომელი შეარჩიოთ')
        .replace(/რომელმა\s+შევურჩიოთ/gi, 'რომელი შევურჩიოთ')
        .replace(/რით\s+შევურჩიოთ\s+დღეს\s+განწყობა/gi, 'რომელი სასუსნავი შევურჩიოთ')
        .replace(/შევურჩიოთ\s+დღეს\s+განწყობა/gi, 'შევურჩიოთ სასუსნავი')
        .replace(/გამარჯობა\s+([ა-ჰ]+ს)!/gi, 'გამარჯობა, $1!')
        .replace(/დაგეხმაროთ\s+დღეს\?/gi, 'დაგეხმაროთ?')
        .replace(/გავახაროთ\s+დღეს\?/gi, 'გავახაროთ?')
        .replace(/\s+დღეს\?/gi, '?')
        .trim();
    }
    return parsed;
  } catch (error) {
    console.error('[AI] Error generating response:', error.message);

    // Warm, natural consultant fallback instead of robotic template
    const cleanMsg = userMessage.trim().toLowerCase();
    if (cleanMsg.includes('მადლობ') || cleanMsg.includes('გაიხარე')) {
      return {
        replyText: 'არაფრის, გაახარეთ თქვენი ცუგა! ❤️ თუ რამე დაგჭირდეთ, აქ ვარ.',
        isOrderReady: false,
      };
    }

    return {
      replyText: 'გამარჯობა! 🐾 ჩვენი ოთხივე ნატურალური სასუსნავი ადგილზე გვაქვს (თათები, ღრუბელი/ფილტვი, სუპერ-კუბები და პუდრა). რომელი გაინტერესებთ თქვენი ცუგასთვის? 🐶',
      isOrderReady: false,
    };
  }
}

