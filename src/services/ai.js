function safeParseJson(text) {
  if (!text) return null;
  let clean = text.trim();
  // Strip markdown code fences if present
  clean = clean.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '').trim();
  try {
    return JSON.parse(clean);
  } catch (e) {
    const match = clean.match(/\{[\s\S]*\}/);
    if (match) {
      try {
        return JSON.parse(match[0]);
      } catch (err) {}
    }

    // Robust Regex extraction if JSON.parse failed due to unescaped newlines/quotes
    const replyMatch = clean.match(/"replyText"\s*:\s*"([\s\S]*?)(?:"\s*,\s*"(?:isOrderReady|isEscalated|order|customerProfileUpdates)"|(?<!\\)"\s*\}|$)/);
    if (replyMatch && replyMatch[1]) {
      let extracted = replyMatch[1]
        .replace(/\\n/g, '\n')
        .replace(/\\"/g, '"')
        .replace(/\\\\/g, '\\')
        .trim();
      return {
        replyText: extracted,
        isOrderReady: false,
        isEscalated: clean.includes('"isEscalated": true') || clean.includes('"isEscalated":true'),
        order: null,
      };
    }

    // Safety fallback: NEVER leak raw JSON strings starting with { to customer
    if (clean.startsWith('{') || clean.includes('"replyText"') || clean.includes('"isOrderReady"')) {
      return {
        replyText: 'გასაგებია! 🐾 გთხოვთ მოგვწეროთ, რაიმე დამატებითი კითხვა ხომ არ გაქვთ თქვენი ცუგასთვის?',
        isOrderReady: false,
        isEscalated: false,
        order: null,
      };
    }

    // If LLM returned raw conversational text instead of JSON, treat it directly as replyText
    return {
      replyText: clean,
      isOrderReady: false,
      isEscalated: false,
      order: null,
    };
  }
}

async function callGemini(apiKey, contents, attempt = 1, isAudio = false, contextOptions = {}) {
  let targetUrl = GEMINI_TEXT_URL;
  if (isAudio) {
    targetUrl = GEMINI_AUDIO_URL;
  } else if (attempt === 2) {
    targetUrl = GEMINI_BACKUP_URL;
  } else if (attempt >= 3) {
    targetUrl = GEMINI_FALLBACK_URL;
  }

  const res = await fetch(`${targetUrl}?key=${apiKey}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      system_instruction: {
        parts: [{ text: buildSystemPrompt(contextOptions) }],
      },
      contents,
      generationConfig: {
        temperature: 0.6,
        responseMimeType: 'application/json',
      },
    }),
  });

  if (!res.ok) {
    const errText = await res.text();
    console.error(`[AI] Gemini API HTTP error (attempt ${attempt} on ${targetUrl}):`, res.status, errText);

    // If rate-limited or 503/404, retry up to 3 attempts with fallbacks
    if ((res.status === 429 || res.status === 503 || res.status === 404) && attempt < 3) {
      console.log(`[AI] Retrying with model attempt ${attempt + 1} after 800ms...`);
      await new Promise((resolve) => setTimeout(resolve, 800));
      return callGemini(apiKey, contents, attempt + 1, isAudio, contextOptions);
    }

    throw new Error(`Gemini error: ${res.status}`);
  }

  const data = await res.json();
  const candidateText = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!candidateText) {
    throw new Error('Empty response from Gemini API');
  }

  return safeParseJson(candidateText);
}

