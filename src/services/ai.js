/**
 * Generates tailored Authority / Feed reply for Facebook comments & groups.
 */
export async function generateFeedCommentReply({
  commenterName = '',
  commentText = '',
  postText = '',
  recentReplies = [],
}) {
  const apiKey = process.env.GEMINI_API_KEY;

  const fallback = {
    publicReply: 'ჩვენც ზუსტად მაგიტომ ვამზადებთ ნატურალურ, დაბალ ტემპერატურაზე გამომშრალ სასუსნავებს, რომ უსაფრთხო და სასარგებლო იყოს. რომელი ჯიშის ცუგა გყავთ? 🐾',
    isDirectInquiry: false,
    privateReply: '',
  };

  if (!apiKey || !commentText.trim()) {
    return fallback;
  }

  const promptContent = `
პოსტის კონტექსტი: "${postText || 'ძაღლების ჯგუფის დისკუსია / ხრამუნას პოსტი'}"
ავტორი/კომენტატორი: "${commenterName}"
კომენტარი: "${commentText}"
`;

  try {
    const res = await fetch(`${GEMINI_TEXT_URL}?key=${apiKey}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        system_instruction: {
          parts: [{ text: buildFeedAuthorityPrompt(recentReplies) }],
        },
        contents: [{ role: 'user', parts: [{ text: promptContent }] }],
        generationConfig: {
          temperature: 0.7, // Higher temperature for high lexical diversity and natural human feel
          responseMimeType: 'application/json',
        },
      }),
    });

    if (!res.ok) {
      console.warn(`[AI Feed] Primary model returned status ${res.status}, retrying with backup...`);
      const backupRes = await fetch(`${GEMINI_BACKUP_URL}?key=${apiKey}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          system_instruction: {
            parts: [{ text: buildFeedAuthorityPrompt(recentReplies) }],
          },
          contents: [{ role: 'user', parts: [{ text: promptContent }] }],
          generationConfig: {
            temperature: 0.7,
            responseMimeType: 'application/json',
          },
        }),
      });
      if (!backupRes.ok) return fallback;
      const data = await backupRes.json();
      const parsed = JSON.parse(data.candidates?.[0]?.content?.parts?.[0]?.text || '{}');
      return {
        publicReply: sanitizePublicComment(parsed.publicReply || fallback.publicReply, commenterName),
        isDirectInquiry: !!parsed.isDirectInquiry,
        privateReply: parsed.privateReply || '',
      };
    }

    const data = await res.json();
    const candidateText = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidateText) return fallback;

    const parsed = JSON.parse(candidateText);
    return {
      publicReply: sanitizePublicComment(parsed.publicReply || fallback.publicReply, commenterName),
      isDirectInquiry: !!parsed.isDirectInquiry,
      privateReply: parsed.privateReply || '',
    };
  } catch (err) {
    console.error('[AI] Feed reply generation failed, using fallback:', err.message);
    return fallback;
  }
}

/**
 * Sanitizes public feed replies: strips markdown artifacts and prohibited opening greetings/names.
 */
function sanitizePublicComment(replyText, commenterName = '') {
  let cleaned = (replyText || '').trim();
  // Strip Markdown bold/italic artifacts
  cleaned = cleaned.replace(/\*\*/g, '').replace(/\*/g, '');
  // Strip opening greetings if LLM ever slips
  cleaned = cleaned.replace(/^(გამარჯობა|სალამი|მოგესალმებით|დილა მშვიდობისა|საღამო მშვიდობისა)[,!\s]*/i, '');
  // Strip leading name addresses e.g. "ანა," or "გიორგი:"
  if (commenterName) {
    const firstName = commenterName.trim().split(' ')[0];
    if (firstName) {
      cleaned = cleaned.replace(new RegExp(`^${firstName}[,!\s]+`, 'i'), '');
    }
  }
  return cleaned.trim();
}

/**
 * Backwards compatible alias for existing handlers.
 */
export async function generateCommentReplies({ commenterName = '', commentText = '', postText = '', recentReplies = [] }) {
  return generateFeedCommentReply({ commenterName, commentText, postText, recentReplies });
}


/**
 * Uses Gemini 2.5 Flash Vision to inspect payment receipts, extract bank & amount,
 * and verify transfer status against expected order details.
 */
export async function verifyReceiptImage(imageUrl, expectedAmount = null) {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || !imageUrl) return { isReceipt: false };

  try {
    const imgRes = await fetch(imageUrl);
    if (!imgRes.ok) return { isReceipt: false };
    const arrayBuf = await imgRes.arrayBuffer();
    const base64Data = Buffer.from(arrayBuf).toString('base64');
    const contentType = imgRes.headers.get('content-type') || 'image/jpeg';
    const mimeType = contentType.split(';')[0].trim() || 'image/jpeg';

    const prompt = `შეაფასე ეს სურათი: არის თუ არა ეს საბანკო გადარიცხვის ქვითარი (TBC Bank, Bank of Georgia / BOG, Liberty Bank ან სხვა ქართული ბანკი)?
ჩვენი საბანკო ანგარიშები და მიმღების ინიციალებია:
- TBC: GE89TB7331945061100067
- BOG: GE86BG0000000570774787
- მიმღები: ლ.ხ. (ლაშა ხიჯაკაძე / Lasha Khijakadze / ხრამუნა)

ამოიღე შემდეგი მონაცემები:
1. isReceipt: boolean (მკაცრად true მხოლოდ მაშინ, თუ ეს არის ნამდვილი საბანკო გადარიცხვის ქვითარი/სქრინშოტი. თუ ძაღლის ფოტოა, მემია, ჩათის სქრინია ან სხვა რამეა, აუცილებლად დააბრუნე false!)
2. bank: ბანკის დასახელება (TBC / BOG / LIBERTY / CREDO / OTHER / NONE)
3. amount: გადარიცხული თანხა ლარში (მხოლოდ რიცხვი, float, მაგ. 49.50 ან 15)
4. recipient: მიმღების სახელი/ინიციალები ქვითარზე (ჩვენი ინიციალებია: ლ.ხ.)
5. matchesAccount: boolean (არის თუ არა მიმღები ლ.ხ. / ლაშა / ხრამუნა ან ემთხვევა თუ არა ჩვენს IBAN-ს)
6. isSuccessful: boolean (შესრულებულია/წარმატებულია გადარიცხვა თუ მოლოდინშია/ჩაიშალა)
7. matchesExpected: boolean (${expectedAmount ? `მოსალოდნელი თანხაა ${expectedAmount}₾. ემთხვევა თუ არა გადარიცხული თანხა მოსალოდნელს (>= ${expectedAmount})?` : 'true'})
8. transactionId: გადარიცხვის კოდი/იდენტიფიკატორი (თუ ჩანს, ან null)
9. note: მოკლე შეფასება ქართულად

დააბრუნე მხოლოდ სუფთა JSON ობიექტი:
{
  "isReceipt": true,
  "bank": "TBC",
  "amount": 49.50,
  "recipient": "ლ.ხ.",
  "matchesAccount": true,
  "isSuccessful": true,
  "matchesExpected": true,
  "transactionId": "12345678",
  "note": "49.50 ლარის გადარიცხვა TBC-დან ლ.ხ.-ზე წარმატებით შესრულდა"
}`;

    const res = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{
          role: 'user',
          parts: [
            { inlineData: { mimeType, data: base64Data } },
            { text: prompt }
          ]
        }],
        generationConfig: {
          temperature: 0.1,
          responseMimeType: 'application/json'
        }
      })
    });

    if (!res.ok) return { isReceipt: false };
    const data = await res.json();
    const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!text) return { isReceipt: false };
    const cleanJson = text.replace(/^```json/i, '').replace(/```$/i, '').trim();
    const parsed = JSON.parse(cleanJson);
    return parsed;
  } catch (err) {
    console.error('[AI Receipt OCR Error]:', err.message);
    return { isReceipt: false };
  }
}
